import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { PGlite } from '@electric-sql/pglite';

// Generate from disposable PostgreSQL, never from a privileged runtime connection.
export async function integrationSchemaSource() {
  const root = new URL('../supabase/migrations/', import.meta.url);
  const files = (await readdir(root)).filter(file => file.endsWith('.sql')).sort();
  const database = new PGlite();
  const hashes: string[] = [];
  try {
    await database.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key, email text, raw_app_meta_data jsonb default '{}'::jsonb);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;`);
    for (const file of files) {
      const sql = (await readFile(new URL(file, root), 'utf8')).replace(/\r\n/g, '\n');
      hashes.push(`${file}: ${createHash('sha256').update(sql).digest('hex')}`);
      await database.exec(sql);
    }
    const { rows } = await database.query<{ table_name: string; column_name: string; data_type: string; is_nullable: string }>(`
      select table_name, column_name, data_type, is_nullable from information_schema.columns
      where table_schema = 'public' order by table_name, ordinal_position`);
    const types: Record<string, string> = { uuid: 'string', text: 'string', date: 'string',
      'timestamp with time zone': 'string', boolean: 'boolean', integer: 'number', bigint: 'decimal', numeric: 'decimal', jsonb: 'json' };
    const tables = new Map<string, string[]>();
    for (const row of rows) {
      const kind = types[row.data_type];
      if (!kind) throw new Error(`Unmapped SQL type: ${row.data_type}`);
      const columns = tables.get(row.table_name) ?? [];
      columns.push(`    ${row.column_name}: ['${kind}', ${row.is_nullable === 'YES'}],`);
      tables.set(row.table_name, columns);
    }
    return `// Generated by npm run integration:schema --workspace backend. Do not edit.\n` +
      hashes.map(hash => `// ${hash}\n`).join('') +
      `// Decimal wire values are strings; conversion to display numbers is explicit.\n` +
      `export const databaseSchema = {\n` + [...tables].map(([table, columns]) =>
        `  ${table}: {\n${columns.join('\n')}\n  },`).join('\n') + `\n} as const;\n\n` +
      `export type Table = keyof typeof databaseSchema;\n` +
      `type Value<K> = K extends 'string' | 'decimal' ? string : K extends 'number' ? number : K extends 'boolean' ? boolean : unknown;\n` +
      `type Column<C> = C extends readonly [infer K, infer N] ? Value<K> | (N extends true ? null : never) : never;\n` +
      `export type Row<T extends Table> = { [C in keyof typeof databaseSchema[T]]: Column<typeof databaseSchema[T][C]> };\n`;
  } finally { await database.close(); }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const target = new URL('../../Frontend/src/lib/data/database.generated.ts', import.meta.url);
  const source = await integrationSchemaSource();
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== source) throw new Error('Integration schema is stale. Regenerate and review it.');
    console.log('Integration schema matches all local migration sources.');
  } else {
    await writeFile(target, source);
    console.log('Generated the frontend integration schema from disposable PostgreSQL.');
  }
}
